/** 拼接完整行政区划名称，如：西藏自治区昌都市左贡县 */
export function regionFullName(region: Region): string {
  return `${region.province}${region.city}${region.county}`
}

/** 去掉行政区划名称末尾的行政级别后缀，如：朝阳区 -> 朝阳 */
export function regionShortName(name: string): string {
  return name.replace(/(自治县|自治旗|自治州|地区|新区|区|县|市|旗|盟)$/, '')
}

/**
 * 签发机关的市级主体，如：保定市公安局
 * 直辖市没有地级市，直接以省（市）级公安局签发
 */
export function regionAuthorityBase(region: Region): string {
  return `${region.city || region.province}公安局`
}

/** 区县分局名称，如：北京市公安局朝阳分局 */
export function regionAuthorityBranch(region: Region): string {
  return `${regionAuthorityBase(region)}${regionShortName(region.county)}分局`
}

/** 根据 6 位行政区划代码查找行政区划 */
export function findRegionByCode(code: string): Region | undefined {
  return REGIONS.find((item) => item.code === code)
}
